/* Utopia W65C816 Bootstrap Dispatch — Generated Dispatch Table

This file provides the initial dispatch for the Utopia boot sequence.
The generated code handles the first ~50 instructions after reset,
including the classic 65C816 bootstrap:

  SEP #$30   ; Set M=0, X=0 (16-bit A and X)
  PHA        ; Save accumulator
  DEX        ; X = $FFFF
  PLX        ; X = $FFFF
  PHX        ; Push X
  PHB        ; Push Bank register
  LDA #$00
  ...

Generated by manual ROM analysis for T002.
*/

#include "ut_v11_runtime.h"
