#include <stdint.h>
#include <string.h>

/* --- Helper: read byte from ROM at given bank:address --- */
static inline uint8_t rom_read(const SCV11Runtime *r, uint16_t addr) {
    if (!r->machine.rom || addr >= (uint16_t)r->machine.rom_size) return 0;
    /* LoROM: bank 0x80 starts at file offset 0 */
    return r->machine.rom[addr];
}

/* --- Helper: write byte to WRAM --- */
static inline void wram_write(SCV11Runtime *r, uint16_t addr, uint8_t val) {
    if (addr < 0x2000) r->machine.wram[addr] = val;
}

/* --- Helper: read byte from WRAM --- */
static inline uint8_t wram_read(const SCV11Runtime *r, uint16_t addr) {
    if (addr < 0x2000) return r->machine.wram[addr];
    return 0;
}

/* --- Helper: read word from WRAM (little-endian) --- */
static inline uint16_t wram_read16(const SCV11Runtime *r, uint16_t addr) {
    if (addr + 1 >= 0x2000) return 0;
    return (uint16_t)r->machine.wram[addr] | ((uint16_t)r->machine.wram[addr+1] << 8);
}

/* --- Helper: write word to WRAM (little-endian) --- */
static inline void wram_write16(SCV11Runtime *r, uint16_t addr, uint16_t val) {
    if (addr + 1 >= 0x2000) return;
    r->machine.wram[addr]     = (uint8_t)(val & 0xFF);
    r->machine.wram[addr + 1] = (uint8_t)((val >> 8) & 0xFF);
}

/* --- Helper: read byte from MMIO / I/O --- */
static inline uint8_t io_read(const SCV11Runtime *r, uint16_t addr) {
    size_t idx = addr - SC_MMIO_BASE;
    if (idx < sizeof(r->machine.mmio)) return r->machine.mmio[idx];
    return 0xFF;
}

/* --- Helper: write byte to MMIO / I/O --- */
static inline void io_write(SCV11Runtime *r, uint16_t addr, uint8_t val) {
    size_t idx = addr - SC_MMIO_BASE;
    if (idx < sizeof(r->machine.mmio)) r->machine.mmio[idx] = val;
}

