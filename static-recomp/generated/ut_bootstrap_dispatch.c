static inline int cpu_get_flag(const SCV11Runtime *r, int flag) {
    return (r->machine.cpu.status >> flag) & 1;
}

static inline void cpu_set_flag(SCV11Runtime *r, int flag, int val) {
    if (val) r->machine.cpu.status |= (1 << flag);
    else     r->machine.cpu.status &= ~(1 << flag);
}

/* Stack operations (65xx style, high-to-low address) */
static inline uint8_t stack_push(SCV11Runtime *r, uint8_t val) {
    uint8_t sp = r->machine.cpu.sp;
    wram_write(r, 0x0100 + sp, val);
    r->machine.cpu.sp = (sp - 1) & 0xFF;
    return val;
}

static inline uint8_t stack_pop(SCV11Runtime *r) {
    r->machine.cpu.sp = (r->machine.cpu.sp + 1) & 0xFF;
    return wram_read(r, 0x0100 + r->machine.cpu.sp);
}

/* ADC */
static inline void adc(SCV11Runtime *r, uint8_t op) {
    uint8_t a = r->machine.cpu.a;
    uint16_t result = (uint16_t)a + op + (cpu_get_flag(r, 0) /* C */);
    r->machine.cpu.a = (uint8_t)result;
    cpu_set_flag(r, 7, result & 0x80);   /* N */
    cpu_set_flag(r, 1, result == 0);      /* Z */
    cpu_set_flag(r, 6, result > 0xFF);    /* V (simplified) */
    cpu_set_flag(r, 0, result > 0xFF);    /* C */
}

/* SBC */
static inline void sbc(SCV11Runtime *r, uint8_t op) {
    uint8_t a = r->machine.cpu.a;
    uint16_t result = (uint16_t)a - op - (cpu_get_flag(r, 0) /* C */);
    r->machine.cpu.a = (uint8_t)result;
    cpu_set_flag(r, 7, result & 0x80);
    cpu_set_flag(r, 1, (uint8_t)result == 0);
    cpu_set_flag(r, 0, result <= 0xFF);
}

/* AND */
static inline void and_op(SCV11Runtime *r, uint8_t op) {
    r->machine.cpu.a &= op;
    cpu_set_flag(r, 7, r->machine.cpu.a & 0x80);
    cpu_set_flag(r, 1, r->machine.cpu.a == 0);
}

/* ORA */
static inline void ora_op(SCV11Runtime *r, uint8_t op) {
    r->machine.cpu.a |= op;
    cpu_set_flag(r, 7, r->machine.cpu.a & 0x80);
    cpu_set_flag(r, 1, r->machine.cpu.a == 0);
}

/* EOR */
static inline void eor_op(SCV11Runtime *r, uint8_t op) {
    r->machine.cpu.a ^= op;
    cpu_set_flag(r, 7, r->machine.cpu.a & 0x80);
    cpu_set_flag(r, 1, r->machine.cpu.a == 0);
}

/* CMP */
static inline void cmp_op(SCV11Runtime *r, uint8_t op) {
    int diff = (int)r->machine.cpu.a - (int)op;
    cpu_set_flag(r, 0, diff >= 0);
    cpu_set_flag(r, 7, diff < 0);
    cpu_set_flag(r, 1, diff == 0);
}

/* DEC */
static inline void dec_op(SCV11Runtime *r, uint8_t *dest) {
    (*dest)--;
    cpu_set_flag(r, 7, *dest & 0x80);
    cpu_set_flag(r, 1, *dest == 0);
}

/* INC */
static inline void inc_op(SCV11Runtime *r, uint8_t *dest) {
    (*dest)++;
    cpu_set_flag(r, 7, *dest & 0x80);
    cpu_set_flag(r, 1, *dest == 0);
}

/* LSR */
static inline void lsr_op(SCV11Runtime *r, uint8_t *dest) {
    uint8_t old = *dest;
    cpu_set_flag(r, 0, old & 1);
    *dest >>= 1;
    cpu_set_flag(r, 7, *dest & 0x80);
    cpu_set_flag(r, 1, *dest == 0);
}

/* ASL */
static inline void asl_op(SCV11Runtime *r, uint8_t *dest) {
    cpu_set_flag(r, 0, *dest & 0x80);
    *dest <<= 1;
    cpu_set_flag(r, 7, *dest & 0x80);
    cpu_set_flag(r, 1, *dest == 0);
}

/* RTI handler — end of bootstrap */
static void handle_rti(SCV11Runtime *r) {
    uint8_t status = stack_pop(r);
    uint16_t pc_lo = stack_pop(r);
    uint16_t pc_hi = stack_pop(r);
    r->machine.cpu.pc = (uint16_t)((pc_hi << 8) | pc_lo);
    r->machine.cpu.status = (uint8_t)(status | 0x30); /* B and U always 1 */
}


